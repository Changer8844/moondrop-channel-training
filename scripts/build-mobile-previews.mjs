// Resize only display previews. Original photographs and gallery downloads are never overwritten.
import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import {pathToFileURL,fileURLToPath} from 'node:url';
import {createRequire} from 'node:module';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const modules=path.resolve(path.dirname(process.execPath),'../node_modules');
const require=createRequire(path.join(modules,'sharp/package.json')),sharp=require('sharp');
const {chromium}=await import(pathToFileURL(path.join(modules,'playwright/index.mjs')));
const browser=await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
const context=await browser.newContext({offline:true});
await context.addInitScript(()=>{if(location.protocol==='file:')localStorage.setItem('moondropChannelTrainingAccess',JSON.stringify({version:1,expires:Date.now()+3600000}));});
const page=await context.newPage(),sources=new Set();
try{
  for(const product of ['mm3a','pill','pudding','space-travel-2','rays']){
    await page.goto(pathToFileURL(path.join(root,'products',product,'index.html')).href+'?lang=en&section=gallery');
    for(const src of await page.locator('.gallery-card img').evaluateAll(ns=>ns.map(n=>n.src)))sources.add(fileURLToPath(src));
  }
  await page.goto(pathToFileURL(path.join(root,'index.html')).href);
  for(const image of await page.evaluate(()=>[...MOONDROP_TRAINING_CATALOG.products,...MOONDROP_TRAINING_CATALOG.categories].map(p=>p.image)))sources.add(path.resolve(root,image));
}finally{await browser.close();}
const dir=path.join(root,'assets/mobile-previews');await fs.mkdir(dir,{recursive:true});
const manifest={},details=[];let originalBytes=0,previewBytes=0;
for(const input of [...sources].sort()){
  const key=path.relative(root,input).split(path.sep).join('/');
  if(key.startsWith('..')||key.includes('/mobile-previews/'))throw Error('Unexpected source path');
  const file=crypto.createHash('sha256').update(key).digest('hex').slice(0,16)+'.webp';
  const result=await sharp(input).rotate().resize({width:800,height:800,fit:'inside',withoutEnlargement:true}).webp({quality:84}).toFile(path.join(dir,file));
  const bytes=(await fs.stat(input)).size;originalBytes+=bytes;previewBytes+=result.size;
  manifest[key]='assets/mobile-previews/'+file;details.push({source:key,preview:manifest[key],sourceBytes:bytes,previewBytes:result.size,width:result.width,height:result.height});
}
await fs.writeFile(path.join(root,'mobile-previews.js'),'/* Site-root-relative preview map. Generated by scripts/build-mobile-previews.mjs; originals remain unchanged. */\nwindow.MOONDROP_MOBILE_PREVIEWS = '+JSON.stringify(manifest,null,2)+';\n');
await fs.writeFile(path.join(dir,'manifest.json'),JSON.stringify({version:1,originalBytes,previewBytes,images:details},null,2)+'\n');
console.log(JSON.stringify({images:details.length,originalBytes,previewBytes,savedPercent:Math.round((1-previewBytes/originalBytes)*100)},null,2));
